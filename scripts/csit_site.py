HTML_STATE = {
    "pass": "\u2705 passed",
    "fail": "\u274c failed",
    "missing": "\u26a0\ufe0f no results",
}


# Marks a published site so a later summary never counts it as a job.
SITE_MARKER = ".csit-site"

# Drill-downs go here, so a job name never collides with a site file.
JOBS_DIR = "jobs"
SITE_FILES = ("index.html", "report.json", "csit-summary.md", SITE_MARKER)


def write_replacing(target: Path, text: str) -> None:
    """Write text to target by renaming a new file over it, so a planted
    symlink there is replaced rather than written through."""
    fd, tmp = tempfile.mkstemp(prefix=".robot-gate.", dir=target.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.chmod(tmp, 0o644)
        os.replace(tmp, target)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def has_result(directory: Path) -> bool:
    """Whether directory holds an output.xml, even a dangling link; a real
    directory of that name is the drill-down of a job named output.xml."""
    xml = directory / "output.xml"
    return xml.is_symlink() or (xml.exists() and not xml.is_dir())


def site_owned(directory: Path) -> bool:
    """Whether directory is a site: a link-free marker and no result."""
    marker = directory / SITE_MARKER
    return marker.exists() and not linked(marker) and not has_result(directory)


def linked(path: Path) -> bool:
    """Whether path or any ancestor on it, as given, is a symlink; results
    reached through a link are treated as absent, never published."""
    return any(p.is_symlink() for p in (path, *path.parents))


def copy_drilldown(src: Path, dst: Path, skip: Path) -> list[str]:
    """Copy a job's robot report/log into the site; return the copied names.

    log.html's `--splitlog` parts and screenshots travel with it at the
    same relative path. Nothing reached through a symlink is copied, so a
    link to a runner file cannot leak; the walk never enters a published
    site or the drill-down tree (skip), which may sit beneath src.
    """
    if linked(src):
        return []
    names = [
        f
        for f in ("report.html", "log.html")
        if (src / f).is_file() and not (src / f).is_symlink()
    ]
    if not names:
        return names
    dst.mkdir(parents=True, exist_ok=True)
    for f in names:
        shutil.copy2(src / f, dst / f)
    for here, dirs, files in os.walk(src):
        base = Path(here)
        dirs[:] = [
            d
            for d in dirs
            if not (base / d).is_symlink()
            and not site_owned(base / d)
            and (base / d).resolve() != skip
        ]
        rel = base.relative_to(src)
        for f in files:
            path = base / f
            if path.is_symlink() or not any(fnmatch(f, p) for p in SUPPORT_FILES):
                continue
            (dst / rel).mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, dst / rel / f)
    return names


def write_site(
    out: Path,
    rows,
    title: str,
    good: int,
    total_jobs: int,
    results=None,
    created: Path | None = None,
) -> None:
    """Write the published report: a landing page plus machine-readable JSON.

    Each job's own Robot report and log are copied in and linked per row
    (the README says why not rebot). Rows follow the dispatched job list,
    so a job that produced nothing is a visible row, never a gap. created
    is the directory publishing made under results, if any; it is marked
    so later summaries skip it.
    """
    body = []
    jobs = out / JOBS_DIR
    # Marked before any copying, so the walk below and later summaries both
    # treat the site and its drill-down tree as published output, not jobs.
    for marked in (out, created):
        if marked is not None:
            write_replacing(marked / SITE_MARKER, "")
    if results is not None:
        # Rebuilt on every publication, so nothing stale is left behind;
        # html_overlaps_job has refused any jobs directory not the site's.
        if jobs.is_symlink():
            jobs.unlink()
        elif jobs.is_dir():
            shutil.rmtree(jobs)
        jobs.mkdir()
        # A directory, so a job itself named like the marker still has a
        # place for its drill-down; every marker check uses exists().
        (jobs / SITE_MARKER).mkdir()
    for r in rows:
        # Copied rather than linked to the artifact, so the page still works
        # for anyone, including after the 30-day artifact retention expires.
        drill = ""
        if results is not None:
            names = copy_drilldown(results / r["job"], jobs / r["job"], jobs.resolve())
            drill = " ".join(
                f'<a href="{JOBS_DIR}/{quote(r["job"])}/{f}">{f.split(".")[0]}</a>'
                for f in names
            )
        cells = (
            ["\u2013", "\u2013", "\u2013"]
            if r["state"] == "missing"
            else [
                f"{r['passed']}/{r['total']}",
                f"{r['pct']:.2f}%",
                str(r["skipped"]),
            ]
        )
        tds = "".join(f'<td class="num">{c}</td>' for c in cells)
        body.append(
            f'<tr class="{r["state"]}"><td>{escape(r["job"])}</td>{tds}'
            f"<td>{HTML_STATE[r['state']]}</td><td>{drill}</td></tr>"
        )

    links = (
        '<a class="btn" href="csit-summary.md">Markdown \u2192</a>'
        '<a class="btn" href="report.json">JSON \u2192</a>'
    )

    server = os.environ.get("GITHUB_SERVER_URL", "")
    repo = os.environ.get("GITHUB_REPOSITORY", "")
    run_id = os.environ.get("GITHUB_RUN_ID", "")
    run = (
        f' \u00b7 <a href="{server}/{repo}/actions/runs/{run_id}">run {run_id}</a>'
        if server and repo and run_id
        else ""
    )
    ok = total_jobs and good == total_jobs
    write_replacing(
        out / "index.html",
        SITE.format(
            title=escape(title or "CSIT"),
            when=datetime.now(_UTC).strftime("%Y-%m-%d %H:%M UTC"),
            run=run,
            cls="go" if ok else "nogo",
            verdict=(
                f"{good}/{total_jobs} jobs green"
                + (" \u2014 all green" if ok else " \u2014 not all green")
                if total_jobs
                else "\u26a0\ufe0f no jobs to report"
            ),
            links=links,
            rows="\n".join(body),
        ),
    )
    write_replacing(
        out / "report.json",
        json.dumps(
            {
                "title": title,
                "generated": datetime.now(_UTC).isoformat(),
                "run": f"{server}/{repo}/actions/runs/{run_id}" if run_id else "",
                "green": good,
                "jobs": total_jobs,
                "results": rows,
            },
            indent=2,
        )
        + "\n",
    )


MD_STATE = {"pass": "\u2705", "fail": "\u274c", "missing": "\u26a0\ufe0f no results"}


def md_cell(text) -> str:
    """Text safe in one markdown table cell: no pipes or line breaks."""
    return " ".join(str(text).replace("\\", "\\\\").replace("|", "\\|").split())


def md_row(r):
    """One markdown row, with a job that produced nothing still present."""
    job = md_cell(r["job"])
    if r["state"] == "missing":
        return f"| {job} | \u2013 | \u2013 | {MD_STATE['missing']} |"
    return (
        f"| {job} | {r['passed']}/{r['total']} | "
        f"{r['pct']:.2f}% | {MD_STATE[r['state']]} |"
    )


def created_top(root: Path, html: Path) -> Path | None:
    """The directory under root that publishing to html would create, if any.

    Publishing to results/published/site creates results/published, which
    holds no results; it needs the site marker too, or a later summary counts
    it as a job with no output.xml.
    """
    # An absent root is created along with html, so its new top counts too.
    if root.exists() and not root.is_dir():
        return None
    base, target = root.resolve(), html.resolve()
    if target == base or not target.is_relative_to(base):
        return None
    top = base / target.relative_to(base).parts[0]
    return None if top == target or top.exists() else top


def html_overlaps_job(root: Path, html: Path) -> bool:
    """Whether publishing to html would land in a job's own directory.

    A directory holding output.xml is a job. So is an existing, unmarked
    directory directly under the results root: that is a job that crashed
    before writing output.xml, and a site there would hide it. The site
    rebuilds html/jobs, so an unmarked jobs directory there, or one holding
    output.xml, counts too, as does a directory where a site file goes and
    a results root at or under html/jobs.
    """
    # html/jobs is rebuilt from the results, so results in it would be lost.
    jobs, root_r = html / JOBS_DIR, root.resolve()
    if has_result(html) or jobs.resolve() in (root_r, *root_r.parents):
        return True
    # Site files cannot replace a job directory, nor in place a job link
    # (maybe dangling) of that name: it would be lost or fail part-way.
    links = (JOBS_DIR, *SITE_FILES) if html.resolve() == root_r else ()
    if any((html / n).is_dir() for n in SITE_FILES) or any(
        (html / n).is_symlink() for n in links
    ):
        return True
    # The drill-down tree goes in html/jobs; an unmarked one there is a job.
    if jobs.is_dir() and not site_owned(jobs):
        return True
    if not html.is_dir() or site_owned(html) or not root.is_dir():
        return False
    return html.resolve().parent == root.resolve()


def unsafe_links(html: Path) -> list[Path]:
    """Symlinks a publication to html would keep, outside what it rebuilds.

    The Pages upload dereferences links, so one left in the site, such as a
    job's own log.html when publishing in place, would publish its target;
    so would html itself, or an ancestor, being a link.
    """
    if linked(html):
        return [html]
    found = []
    for top, dirs, files in os.walk(html):
        here = Path(top)
        for name in dirs + files:
            rebuilt = here == html and name in (JOBS_DIR, *SITE_FILES)
            if (here / name).is_symlink() and not rebuilt:
                found.append(here / name)
        if here == html:
            dirs[:] = [d for d in dirs if d != JOBS_DIR]
    return found


def discover_jobs(root: Path) -> list[str]:
    """Job directories under root when no job list was given."""
    # A marked site under the results root is not a job; a link is listed
    # whatever its target, so a dangling one still reports missing.
    jobs = [p for p in root.iterdir() if p.is_symlink() or p.is_dir()]
    return sorted(p.name for p in jobs if p.is_symlink() or not site_owned(p))


def job_list(root: Path, listed: str) -> list[str]:
    """The jobs to report: the dispatched list, else whatever arrived.

    Each listed name is joined onto the results root and the site's jobs
    tree, so a path, `.` or `..` would read or write outside both and is
    refused with ValueError.
    """
    if listed:
        lines = Path(listed).read_text(encoding="utf-8").splitlines()
        names = [line.strip() for line in lines if line.strip()]
        bad = [n for n in names if n in (".", "..") or "/" in n or "\\" in n]
        if bad:
            raise ValueError(f"invalid job name(s) in {listed}: {bad}")
        return names
    # A linked root is absent: listing its target would publish the names
    # of directories that are not this run's.
    if root.is_dir() and not linked(root):
        return discover_jobs(root)
    # No job list and nothing downloaded: still render a readable page.
    return []
